"""Pin the sources: canonical ref, tooling, and which text each round judged.

    python experiments/registry-state2-investigation/provenance.py

Writes results/provenance.json and results/rounds.md. Each State 2 round's
summary.json records the sha256 of every document it read; this script finds,
for every round, the earliest commit of the case whose file has that digest,
and lists the round's topics about the cluster (A04, A05, A14, A15, and the
audit/confirmation/numbering subjects wherever the reviewer filed them).
"""
from __future__ import annotations

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE / "model"))
from sources import CANONICAL_REF, CANONICAL_SHA, TOOLS_MAIN_SHA, VERSIONS  # noqa: E402

CASE = "examples/registry"
FILES = ["00_product.md", "01_models.md", "02_rules_audit.md", "02_rules_records.md", "02_rules_access.md",
         "02_rules_installation.md"]
CLUSTER = {"A04", "A05", "A14", "A15"}
SUBJECT = re.compile(r"confirmation id|empty audit|no-op audit|audit erasure|erasure entry|entry-existence|"
                     r"existence invariant|audit sequence|sequence number|high-water|accepted erasure|"
                     r"erasure with no matches", re.I)


def git(*args: str, binary: bool = False):
    out = subprocess.run(["git", *args], capture_output=True, cwd=ROOT)
    return out.stdout if binary else out.stdout.decode()


def main() -> int:
    first = git("rev-list", "--reverse", "--topo-order", f"{VERSIONS['V0']['sha']}^..{CANONICAL_SHA}").split()
    index: dict[tuple[str, str], str] = {}
    for c in first:
        for f in FILES:
            body = git("show", f"{c}:{CASE}/{f}", binary=True)
            if body:
                index.setdefault((f, hashlib.sha256(body).hexdigest()), c[:8])
    rounds = []
    lines = ["# State 2 rounds of Registry: the texts they read and the cluster's topics", "",
             "Generated by `provenance.py`. `texts` gives, per document, the earliest commit whose file has the "
             "digest the round recorded. `n` is the number of reviews that raised the topic (one: never judged).",
             ""]
    for path in sorted((ROOT / CASE / "questions" / "state2").glob("round-*/summary.json")):
        d = json.loads(path.read_text(encoding="utf-8"))
        texts = {f: index.get((f, d["documents"].get(f, ""))) for f in FILES}
        topics = []
        for t in d["topics"]:
            text = t["topic"] + " " + " ".join(t.get("questions", []))
            if set(t.get("units", [])) & CLUSTER or SUBJECT.search(text):
                j = t.get("judgement") or {}
                topics.append({"id": t.get("id"), "n": len(t["members"]), "units": t.get("units"),
                               "kind": j.get("kind"), "blocking": j.get("blocking"), "topic": t["topic"]})
        r = {"round": d["round"], "provider": d["provider"], "texts": texts,
             "scope_has": sorted(CLUSTER & set(d.get("scope") or [])), "changed_units": d.get("changed_units"),
             "blocking_topics": d["blocking_topics"], "topics": topics}
        rounds.append(r)
        lines.append(f"## {d['round']} — audit `{texts['02_rules_audit.md']}`, records `{texts['02_rules_records.md']}`, "
                     f"product `{texts['00_product.md']}`, models `{texts['01_models.md']}`")
        lines.append(f"cluster units in scope: {', '.join(r['scope_has']) or 'none'}; "
                     f"blocking topics in the round: {d['blocking_topics']}")
        for t in topics:
            lines.append(f"- {t['id'] or '—'} (n={t['n']}, {', '.join(t['units'] or [])}) "
                         f"{t['kind'] or 'not judged'}{' BLOCKING' if t['blocking'] else ''}: {t['topic']}")
        lines.append("")
    index_entry = next(p for p in json.loads((ROOT / "PROJECT_INDEX.json").read_text())["projects"]
                       if p["id"] == "registry")
    prov = {
        "canonical_ref": CANONICAL_REF, "canonical_sha": CANONICAL_SHA,
        "origin_canonical_sha_now": git("rev-parse", f"origin/{CANONICAL_REF}").strip(),
        "tools_main_sha": TOOLS_MAIN_SHA,
        "tools_differ_from_main": bool(git("diff", "--stat", TOOLS_MAIN_SHA, CANONICAL_SHA, "--", "tools", "skills")),
        "project_index_entry": index_entry,
        "versions": {k: {**v, "full_sha": git("rev-parse", v["sha"]).strip()} for k, v in VERSIONS.items()},
        "rounds": rounds,
    }
    (HERE / "results").mkdir(exist_ok=True)
    (HERE / "results" / "provenance.json").write_text(json.dumps(prov, ensure_ascii=False, indent=1) + "\n",
                                                      encoding="utf-8")
    (HERE / "results" / "rounds.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rounds)} rounds; canonical {CANONICAL_SHA[:8]}; tools differ from main: {prov['tools_differ_from_main']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
